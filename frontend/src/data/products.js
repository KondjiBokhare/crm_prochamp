export function getProductById(id) {
  const numericId = Number(id);
  return products.find((product) => product.id === numericId) || null;
}

export function getProductsByCategory(category) {
  if (!category) return products;
  const value = category.toLowerCase();
  return products.filter((product) => product.category.toLowerCase() === value);
}

export function getProductsByBrand(brand) {
  if (!brand) return products;
  const value = brand.toLowerCase();
  return products.filter((product) => product.brand.toLowerCase() === value);
}

export function getDeals(limit = 10) {
  return products
    .filter((product) => Number(product.discount || 0) > 0)
    .sort((a, b) => Number(b.discount || 0) - Number(a.discount || 0))
    .slice(0, limit);
}

export function getBestSelling(limit = 10) {
  return [...products]
    .sort((a, b) => {
      const ar = Number(String(a.reviews).replace(/[^0-9.]/g, ""));
      const br = Number(String(b.reviews).replace(/[^0-9.]/g, ""));
      return br - ar;
    })
    .slice(0, limit);
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return [];

  return products
    .filter(
      (item) =>
        item.id !== product.id &&
        (item.category === product.category || item.brand === product.brand)
    )
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
}

export function searchProducts(query) {
  if (!query?.trim()) return products;

  const value = query.toLowerCase().trim();

  return products.filter((product) => {
    const haystack = [
      product.name,
      product.brand,
      product.category,
      product.subcategory,
      product.specs,
      ...product.tags,
    ]
      .join(" ")
      .toLowerCase();

    return haystack.includes(value);
  });
}

